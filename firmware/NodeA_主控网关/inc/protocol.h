/**************************************************************************************************
 * protocol.h  ——  「寝室管家」三机 485 总线通信协议
 *
 *   三块板共用这一个文件，内容必须【完全一致】。任何一方改了这里，三块板都要重新编译下载，
 *   否则会出现「CRC 一直错」或「数据错位」这类很难查的问题。
 *   约定：改这个文件必须三个人都在场，改完立刻同步。
 *
 *   拓扑：  节点A(0x01, 主站)  ---+---  节点B(0x02, 环境节点)
 *                                 |
 *                                 +---  节点C(0x03, 安防节点)
 *           485 半双工总线，A / B / GND 三线并接
 *
 *   通信方式：主站轮询，从站只应答不主动发（半双工总线上不能有两个人同时说话）
 *
 *       主站 --REQ(8字节)--> 从站
 *       主站 <--RSP(16字节)-- 从站
 *
 *   为什么用固定长度帧：
 *       uart2.h 里明确写了，ModBus 模式下 BSP「未返回 ModBus 数据帧有效字节数」，
 *       也就是收到事件时并不知道这一帧有多长。用固定长度就绕开了这个问题——
 *       主站只会收到 16 字节的应答，从站只会收到 8 字节的请求，各自长度唯一。
 *
 *   为什么自己算 CRC：
 *       uart2.h 明确写了「数据帧内未进行 CRC 校验，建议用户在回调函数中自行校验」。
 *       BSP 只负责把一帧字节交给你，正确性要自己保证。
 *
 * 编写：小组共同约定    日期：待填
 **************************************************************************************************/
#ifndef _PROTOCOL_H_
#define _PROTOCOL_H_

/*==================================================================================================
 * 一、总线参数
 *================================================================================================*/

/* 485 波特率。三块板必须一致。
   9600 下：8 字节请求约 8.3mS，16 字节应答约 16.7mS，一次问答约 40mS，两个从站轮询一圈约 180mS。
   如果现场干扰大、丢帧多，把这里和三块板一起降到 1200（hw5-0 里验证过的速率），可靠性更高。   */
#define BUS_BAUD            9600

/* 断帧方式开关。三块板必须一致。
     1 = Uart2Usedfor485ModBus  按【字节间隔】断帧，工业协议方式，推荐
     0 = Uart2Usedfor485        按【固定长度 + 包头匹配】断帧，hw5-0 题2 验证过的方式

   ModBus 方式更好的原因：从站在总线上不仅能听到主站的请求，也能听到另一个从站的应答。
   按固定长度断帧时，另一个从站那 16 字节应答会被误当成两个 8 字节请求去解析，
   其中第二段的首字节是数据内容，有小概率恰好等于本机地址而通过包头匹配——
   最后还得靠 CRC 把它挡掉。按字节间隔断帧则从根上不会拆错帧。
   两种方式我们都实现了，联调时哪个稳用哪个，改这一个宏，三块板重新编译即可。         */
#define BUS_USE_MODBUS      1


/*==================================================================================================
 * 二、节点地址
 *================================================================================================*/
#define ADDR_MASTER         0x01        /* 节点A：主控 / 网关 */
#define ADDR_ENV            0x02        /* 节点B：环境节点（窗台） */
#define ADDR_SEC            0x03        /* 节点C：安防节点（门口） */


/*==================================================================================================
 * 三、功能码
 *================================================================================================*/
#define FUNC_POLL           0x03        /* 主站轮询：读从站全部状态 */
#define FUNC_SETCFG         0x10        /* 主站下发配置参数 */
#define FUNC_ACT            0x06        /* 主站直接命令执行器（联调 / 演示用） */


/*==================================================================================================
 * 四、帧格式
 *
 *   请求 REQ（主站 -> 从站），固定 8 字节：
 *       [0] addr    目标从站地址
 *       [1] func    功能码
 *       [2] arg0    参数，含义由功能码决定
 *       [3] arg1
 *       [4] arg2
 *       [5] arg3
 *       [6] crcLo   CRC16 低字节（ModBus 惯例：低字节在前）
 *       [7] crcHi
 *
 *   应答 RSP（从站 -> 主站），固定 16 字节：
 *       [0]     addr    从站回显自己的地址
 *       [1]     func    回显功能码
 *       [2..13] data    12 字节数据区，布局见下面第五节
 *       [14]    crcLo
 *       [15]    crcHi
 *================================================================================================*/
#define REQ_LEN             8
#define RSP_LEN             16

#define F_ADDR              0           /* 两种帧共用的字段偏移 */
#define F_FUNC              1
#define REQ_ARG0            2
#define REQ_ARG1            3
#define REQ_ARG2            4
#define REQ_ARG3            5
#define RSP_DATA            2           /* 应答数据区起始偏移 */

/* FUNC_SETCFG 的参数含义（发给不同从站含义不同）
     发给 ENV(0x02)： arg0 = 风扇启动温度阈值(摄氏度)   arg1 = 保留   arg2/arg3 = 保留
     发给 SEC(0x03)： arg0 = 布防 0/1                  arg1 = 接近提示阈值(cm)   arg2/arg3 = 保留
   FUNC_ACT 的参数含义
     发给 ENV(0x02)： arg0 = 手动风扇占空比 0~100，255 表示交回自动控制
     发给 SEC(0x03)： arg0 = 1 上锁 / 0 开锁                                          */


/*==================================================================================================
 * 五、应答数据区（RSP[2..13]）布局
 *   下面的偏移量都是相对 RSP_DATA 的，取用时写 RspBuf[RSP_DATA + D_ENV_LUX] 这样
 *================================================================================================*/

/* ---- 节点类型，放在数据区第 0 字节，主站靠它确认对方是谁 ---- */
#define NODE_TYPE_ENV       0x0B
#define NODE_TYPE_SEC       0x0C

/* ---- 节点B 环境节点 ---- */
#define D_ENV_TYPE          0           /* = NODE_TYPE_ENV */
#define D_ENV_FLAGS         1           /* 状态位，见下面 ENVF_xxx */
#define D_ENV_TEMP_H        2           /* 温度 x10，有符号 16 位，高字节在前。235 表示 23.5 摄氏度 */
#define D_ENV_TEMP_L        3
#define D_ENV_LUX           4           /* 光照档位 0(最暗) ~ 4(最亮) */
#define D_ENV_FAN           5           /* 风扇当前占空比 0~100 */
#define D_ENV_RAWRT_H       6           /* 热敏电阻原始 ADC 值，标定时要看，所以一并传上去 */
#define D_ENV_RAWRT_L       7
#define D_ENV_RAWROP_H      8           /* 光敏电阻原始 ADC 值 */
#define D_ENV_RAWROP_L      9
#define D_ENV_MISS          10          /* 本节点每秒轮询丢失数（GetSysPerformance），观察 1mS 约束用 */
#define D_ENV_RSV           11

#define ENVF_FAN_ON         0x01        /* bit0 风扇在转 */
#define ENVF_WIN_OPEN       0x02        /* bit1 通风窗已打开 */
#define ENVF_TEMP_HI        0x04        /* bit2 高温告警 */
#define ENVF_LUX_LOW        0x08        /* bit3 光线过暗 */

/* ---- 节点C 安防节点 ---- */
#define D_SEC_TYPE          0           /* = NODE_TYPE_SEC */
#define D_SEC_FLAGS         1           /* 状态位，见下面 SECF_xxx */
#define D_SEC_DIST_H        2           /* 超声波距离 cm，有符号 16 位，高字节在前。-1 表示无效 */
#define D_SEC_DIST_L        3
#define D_SEC_ALARM         4           /* 报警等级 0 无 / 1 提示 / 2 报警 */
#define D_SEC_VIBCNT        5           /* 累计有效振动次数 */
#define D_SEC_DOORCNT       6           /* 累计开门次数 */
#define D_SEC_STATE         7           /* 布防状态机当前状态，见下面 SECST_xxx */
#define D_SEC_RSV8          8
#define D_SEC_RSV9          9
#define D_SEC_RSV10         10
#define D_SEC_MISS          11          /* 每秒轮询丢失数 */

#define SECF_ARMED          0x01        /* bit0 已布防 */
#define SECF_DOOR_OPEN      0x02        /* bit1 门开着 */
#define SECF_VIB            0x04        /* bit2 检测到异动 */
#define SECF_NEAR           0x08        /* bit3 门口有人靠近 */
#define SECF_LOCKED         0x10        /* bit4 锁舌在锁上位置 */

#define SECST_DISARMED      0           /* 撤防 */
#define SECST_ARMING        1           /* 布防倒计时中（给自己留出门时间） */
#define SECST_ARMED         2           /* 已布防 */
#define SECST_ALARM         3           /* 报警中 */

/* ---- 报警等级 ---- */
#define ALM_NONE            0
#define ALM_NOTICE          1           /* 提示：蜂鸣器短鸣 */
#define ALM_ALARM           2           /* 报警：循环播放报警旋律 */


/*==================================================================================================
 * 六、红外指令（节点C 发 -> 节点A 收，作为 485 之外的第二条无线链路）
 *   IR 通信没有包头匹配功能（见 uart2.h 补充说明），所以自己在数据里放一个帧头字节。
 *================================================================================================*/
#define IR_LEN              3
#define IR_HDR              0x5A        /* [0] 帧头 */
                                        /* [1] 命令 */
                                        /* [2] 校验 = 帧头 ^ 命令 ^ 0xFF */
#define IR_CMD_TOGGLE_ARM   0x01        /* 切换布防 / 撤防 */
#define IR_CMD_ALARM        0x02        /* 报警发生 */
#define IR_CMD_SILENCE      0x03        /* 消音 */


/*==================================================================================================
 * 七、节点A 的 M24C02 参数存储布局
 *   开机先看 0 号单元是不是 NVM_MAGIC，再看校验和对不对，两个都对才用存的参数，
 *   否则用出厂默认值。这样第一次上电、或者 EEPROM 内容被写乱时不会读出一堆乱参数。
 *================================================================================================*/
#define NVM_MAGIC           0xA5
#define NVM_A_MAGIC         0           /* [0] 幻数 */
#define NVM_A_TEMPSET       1           /* [1] 风扇启动温度阈值 摄氏度 */
#define NVM_A_ARM           2           /* [2] 布防开关 0/1 */
#define NVM_A_ALARM_H       3           /* [3] 闹钟 时 */
#define NVM_A_ALARM_M       4           /* [4] 闹钟 分 */
#define NVM_A_NEARCM        5           /* [5] 接近提示阈值 cm */
#define NVM_A_SUM           6           /* [6] 校验和 = [1]+[2]+[3]+[4]+[5] 的低 8 位 */
#define NVM_A_COUNT         7

/* 出厂默认参数 */
#define DEF_TEMPSET         28          /* 28 摄氏度以上开风扇 */
#define DEF_ARM             0           /* 默认不布防 */
#define DEF_ALARM_H         7           /* 默认闹钟 07:00 */
#define DEF_ALARM_M         0
#define DEF_NEARCM          60          /* 60cm 以内认为有人靠近 */


/*==================================================================================================
 * 八、公共小函数
 *
 *   注意：这几个函数直接【定义】在头文件里，不是只做声明。
 *   因为每个工程只有一个 main.c 包含它，不会产生重复定义；
 *   这样做能保证三块板用的是【一模一样】的 CRC 和打包代码——协议出问题时可以先排除这一项。
 *================================================================================================*/

/*----------------------------------------------------------------------------------
 * 16 位大端打包 / 解包
 *   8051 上不同写法的字节序容易搞混，统一走这两个函数，三块板就不会出现高低字节颠倒
 *
 *   ！！按需编译：每个节点其实只用得到一个方向——主站只解包(GetI16)，从站只打包(PutI16)。
 *   C51【不做死代码剔除】，没被调用的函数照样占代码空间，链接时那条
 *       WARNING L16: UNCALLED SEGMENT, IGNORED FOR OVERLAY PROCESS
 *           SEGMENT: ?PR?_PUTI16?MAIN
 *   说的就是这件事。Keil Eval 版只有 2KB 用户代码额度，这种白占必须掐掉。
 *   各 main.c 在 #include "protocol.h" 之前定义 PROTO_NO_PUTI16 或 PROTO_NO_GETI16。
 *   忘了定义只是浪费几十字节，不会编译不过，所以默认两个都编。
 *---------------------------------------------------------------------------------*/
#ifndef PROTO_NO_PUTI16
static void PutI16(unsigned char *p, int v)
{
	p[0] = (unsigned char)((unsigned int)v >> 8);
	p[1] = (unsigned char)((unsigned int)v & 0x00FF);
}
#endif

#ifndef PROTO_NO_GETI16
static int GetI16(unsigned char *p)
{
	unsigned int u = (unsigned int)(((unsigned int)p[0] << 8) | (unsigned int)p[1]);

#ifdef __C51__
	/* Keil C51 的 int 就是 16 位，这一步转换本身就是补码还原，不需要任何额外运算。
	   走下面那条通用分支的话会拖进 long 运算库，白花几十字节。 */
	return (int)u;
#else
	/* 电脑上跑自测时 int 是 32 位，(int)0xFFFF 会变成 65535 而不是 -1，必须显式还原。
	   距离无效时传的 -1、冬天的负温度都会走到这条路径。 */
	if(u & 0x8000u) return (int)((long)u - 65536L);
	return (int)u;
#endif
}
#endif

/*----------------------------------------------------------------------------------
 * ModBus CRC16
 *   多项式 0xA001（0x8005 反序），初值 0xFFFF，低字节在前
 *   16 字节数据约 128 次移位，在 11.0592MHz 下约几十微秒，不会撞 sys 的 1mS 约束
 *---------------------------------------------------------------------------------*/
static unsigned int Crc16Modbus(unsigned char *buf, unsigned char len)
{
	unsigned int crc = 0xFFFF;
	unsigned char i, j;

	for(i = 0; i < len; i++)
	{
		crc ^= (unsigned int)buf[i];
		for(j = 0; j < 8; j++)
		{
			if(crc & 0x0001)  crc = (crc >> 1) ^ 0xA001;
			else              crc =  crc >> 1;
		}
	}
	return crc;
}

/*----------------------------------------------------------------------------------
 * 下面两个是给 Crc16Modbus 包一层的便利函数。
 * 从站各调用一次，留着很划算；但主站只在两个地方各用一次，
 * 为一次调用养一个函数不值（两个函数体加起来 138 字节，占 2KB 额度的 7%），
 * 所以节点A 定义 PROTO_NO_FRAMECRC，把这两句直接写在调用点上。
 *---------------------------------------------------------------------------------*/
#ifndef PROTO_NO_FRAMECRC
/*----------------------------------------------------------------------------------
 * 给一帧补上 CRC（写进最后两个字节）。len 是整帧长度，含 CRC 那两字节
 *---------------------------------------------------------------------------------*/
static void FrameSetCrc(unsigned char *buf, unsigned char len)
{
	unsigned int crc = Crc16Modbus(buf, (unsigned char)(len - 2));
	buf[len - 2] = (unsigned char)(crc & 0x00FF);      /* 低字节在前 */
	buf[len - 1] = (unsigned char)(crc >> 8);
}

/*----------------------------------------------------------------------------------
 * 校验一帧的 CRC。返回 1 = 正确，0 = 错误
 *---------------------------------------------------------------------------------*/
static unsigned char FrameCrcOk(unsigned char *buf, unsigned char len)
{
	unsigned int crc = Crc16Modbus(buf, (unsigned char)(len - 2));

	if(buf[len - 2] != (unsigned char)(crc & 0x00FF)) return 0;
	if(buf[len - 1] != (unsigned char)(crc >> 8))     return 0;
	return 1;
}
#endif  /* PROTO_NO_FRAMECRC */

#endif
